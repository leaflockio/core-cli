// snapshotPatterns registers a t.Cleanup that truncates patterns back to
// its current length — so a test calling ApplyOverrides never leaks an
// appended pattern into any other test in this package.
func snapshotPatterns(t *testing.T) {
	t.Helper()
	n := len(patterns)
	t.Cleanup(func() {
		patterns = patterns[:n]
	})
}

func TestIsGenerated_builtinPatterns(t *testing.T) {
	tests := []struct {
		name    string
		content string
		want    bool
	}{
		{
			name:    "go generate",
			content: "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage foo\n",
			want:    true,
		},
		{
			name:    "cargo raze",
			content: "DO NOT EDIT! Replaced on runs of cargo-raze\n",
			want:    true,
		},
		{
			name:    "protoc C++/Java/Python/Ruby/PHP/Objective-C",
			content: "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
			want:    true,
		},
		{
			name:    "protoc JS target",
			content: "// source: foo.proto\n/* eslint-disable */\n// GENERATED CODE -- DO NOT EDIT!\n",
			want:    true,
		},
		{
			name:    "go-to-protobuf",
			content: "// This file was autogenerated by go-to-protobuf. Do not edit it manually!\n",
			want:    true,
		},
		{
			name:    "apache thrift",
			content: "# Autogenerated by Thrift Compiler (0.19.0)\n",
			want:    true,
		},
		{
			name:    "jni header",
			content: "/* DO NOT EDIT THIS FILE - it is machine generated */\n#include <jni.h>\n",
			want:    true,
		},
		{
			name:    "ordinary hand-written file",
			content: "package foo\n\nfunc Foo() {}\n",
			want:    false,
		},
		{
			name:    "empty content",
			content: "",
			want:    false,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := IsGenerated([]byte(tt.content)); got != tt.want {
				t.Errorf("IsGenerated(%q) = %v, want %v", tt.content, got, tt.want)
			}
		})
	}
}

func TestApplyOverrides_addsPattern(t *testing.T) {
	snapshotPatterns(t)

	content := []byte("# This file is maintained automatically, do not edit\n")
	if IsGenerated(content) {
		t.Fatal("precondition failed: content already matches a built-in pattern")
	}

	if err := ApplyOverrides([]string{`maintained automatically, do not edit`}); err != nil {
		t.Fatalf("ApplyOverrides: %v", err)
	}

	if !IsGenerated(content) {
		t.Error("IsGenerated = false after ApplyOverrides, want true")
	}
}

func TestApplyOverrides_nilIsNoop(t *testing.T) {
	snapshotPatterns(t)

	if err := ApplyOverrides(nil); err != nil {
		t.Fatalf("ApplyOverrides(nil): %v", err)
	}
}

func TestApplyOverrides_invalidPatternIsCallerError(t *testing.T) {
	snapshotPatterns(t)
	before := len(patterns)

	err := ApplyOverrides([]string{`[unclosed`})
	if err == nil {
		t.Fatal("expected error, got nil")
	}
	var e *errs.Error
	if !errors.As(err, &e) {
		t.Fatalf("error is not an *errs.Error: %v", err)
	}
	if e.Code != errs.GEN001 {
		t.Errorf("Code = %q, want %q", e.Code, errs.GEN001)
	}
	if len(patterns) != before {
		t.Errorf("len(patterns) = %d, want unchanged %d", len(patterns), before)
	}
}

func TestApplyOverrides_allOrNothing(t *testing.T) {
	snapshotPatterns(t)
	before := len(patterns)

	err := ApplyOverrides([]string{`valid-pattern`, `[unclosed`})
	if err == nil {
		t.Fatal("expected error, got nil")
	}
	if len(patterns) != before {
		t.Errorf("len(patterns) = %d, want unchanged %d (neither pattern should be applied)", len(patterns), before)
	}
}
