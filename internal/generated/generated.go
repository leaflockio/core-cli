// Package generated detects whether a file is machine-generated, so
// tools that modify source files can leave it alone. It has no
// dependency on license headers or any other specific caller — the
// question "was this generated" is useful on its own.
package generated

import (
	"regexp"

	"github.com/leaflockio/core-cli/internal/errs"
)

// patterns holds every regex IsGenerated checks against.
var patterns = []*regexp.Regexp{
	// go generate; also covers ts-proto and twirp-ruby, which reuse this phrasing
	regexp.MustCompile(`(?m)^.{1,2} Code generated .* DO NOT EDIT\.$`),
	// cargo raze
	regexp.MustCompile(`(?m)^DO NOT EDIT! Replaced on runs of cargo-raze$`),
	// protoc (C++/Java/Python/Ruby/PHP/Objective-C)
	regexp.MustCompile(`Generated by the protocol buffer compiler\.\s+DO NOT EDIT!`),
	// protoc, JS target
	regexp.MustCompile(`GENERATED CODE -- DO NOT EDIT!`),
	// go-to-protobuf
	regexp.MustCompile(`This file was autogenerated by go-to-protobuf`),
	// Apache Thrift
	regexp.MustCompile(`Autogenerated by Thrift Compiler`),
	// JNI header generator
	regexp.MustCompile(`DO NOT EDIT THIS FILE - it is machine generated`),
}

// IsGenerated reports whether content contains a recognized
// generated-file marker: a built-in convention (Go, cargo-raze), or a
// pattern added via ApplyOverrides.
func IsGenerated(content []byte) bool {
	for _, re := range patterns {
		if re.Match(content) {
			return true
		}
	}
	return false
}

// ApplyOverrides compiles raw and adds the results to the set IsGenerated
// checks, alongside the built-in conventions. All patterns must compile
// for any to be applied, on error, none of the patterns from this call
// are added.
func ApplyOverrides(raw []string) error {
	compiled := make([]*regexp.Regexp, 0, len(raw))
	for _, p := range raw {
		re, err := regexp.Compile(p)
		if err != nil {
			return errs.Caller(errs.GEN001,
				"generated-file pattern is not a valid regular expression",
				err,
				errs.Context{
					Cause:      "pattern " + p + " could not be compiled as a regular expression",
					Resolution: "fix the pattern's regular expression syntax",
				},
			)
		}
		compiled = append(compiled, re)
	}
	patterns = append(patterns, compiled...)
	return nil
}
